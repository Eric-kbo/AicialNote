import { DRIVE_TRANSLATIONS } from './locales'

/**
 * The languages written inline in `Localized` values, and the only ones with their own path names and README.
 * `zh` is Simplified Chinese; the code is kept because existing vault.json files store it. Other languages
 * translate labels through `DRIVE_TRANSLATIONS` (see `pick`), and any tag falls back along `fallbackChain` to `en`.
 */
export const LOCALES = ['zh', 'en'] as const
export type Locale = (typeof LOCALES)[number]

/** A string in English plus any number of translations. */
export type Localized = { en: string } & Partial<Record<Locale, string>>

/**
 * The tags to try for `tag`, most specific first, always ending at `en`.
 * `pt-BR` → `pt-BR, pt, en`; `zh-TW` → `zh-TW, zh-Hant, zh, en`; `zh-CN` → `zh-CN, zh, en`.
 */
export function fallbackChain(tag: string): string[] {
  const out: string[] = []
  const add = (t: string) => {
    if (t && !out.includes(t)) out.push(t)
  }
  let canonical = tag
  try {
    canonical = Intl.getCanonicalLocales(tag)[0] ?? tag
  } catch {
    // Not a valid BCP 47 tag; use it as given and still end at English.
  }
  add(canonical)
  const parts = canonical.split('-')
  const lang = parts[0]!.toLowerCase()
  if (lang === 'zh') {
    const traditional = parts.some((p) => ['Hant', 'TW', 'HK', 'MO'].includes(p))
    if (traditional) add('zh-Hant')
    else if (parts.length > 1) add('zh-Hans')
  } else if (parts.length > 2) {
    add(parts.slice(0, 2).join('-'))
  }
  add(lang)
  add('en')
  return out
}

/** The first tag in `tag`'s fallback chain that `supported` contains, or `en`. */
export function matchLocale<T extends string>(tag: string, supported: readonly T[]): T | 'en' {
  for (const t of fallbackChain(tag)) {
    const hit = supported.find((s) => s.toLowerCase() === t.toLowerCase())
    if (hit) return hit
  }
  return 'en'
}

/** The best language among `LOCALES` for any tag, including tags this version has no translations for. */
export function resolveLocale(tag: string): Locale {
  return matchLocale(tag, LOCALES)
}

/**
 * `l` in `locale`: the first tag along its fallback chain that `l` itself or `DRIVE_TRANSLATIONS` (keyed by the
 * English text) has. Use `pickPath` for file and folder names.
 */
export function pick(l: Localized, locale: string): string {
  for (const tag of fallbackChain(locale)) {
    const own = (l as Record<string, string | undefined>)[tag]
    if (own !== undefined) return own
    const shared = DRIVE_TRANSLATIONS[tag]?.[l.en]
    if (shared !== undefined) return shared
  }
  return l.en
}

/**
 * Like `pick`, but only ever zh or en. Path names must not follow new translations: adding a language would
 * otherwise move the files of every existing vault in that language and leave the old copies behind (D17).
 */
export function pickPath(l: Localized, locale: string): string {
  return l[resolveLocale(locale)] ?? l.en
}

